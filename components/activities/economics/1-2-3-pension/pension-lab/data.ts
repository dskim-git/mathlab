export type Sex = "male" | "female";

/** 통계청 생명표(2023년) 기준 기대여명 — 5세 간격 개략치(년) */
const LIFE_TABLE: Record<Sex, Record<number, number>> = {
  male: { 55: 27.7, 60: 23.2, 65: 19.0, 70: 15.0, 75: 11.4, 80: 8.3 },
  female: { 55: 32.9, 60: 28.0, 65: 23.7, 70: 19.2, 75: 14.9, 80: 10.9 },
};

/** 나이에 대한 기대여명(년) — 표 사이는 직선보간 */
export function lifeExpectancy(age: number, sex: Sex): number {
  const t = LIFE_TABLE[sex];
  const ages = Object.keys(t).map(Number).sort((a, b) => a - b);
  if (age <= ages[0]) return t[ages[0]];
  if (age >= ages[ages.length - 1]) return t[ages[ages.length - 1]];
  for (let i = 0; i < ages.length - 1; i++) {
    const a0 = ages[i], a1 = ages[i + 1];
    if (age >= a0 && age <= a1) {
      const u = (age - a0) / (a1 - a0);
      return t[a0] + (t[a1] - t[a0]) * u;
    }
  }
  return t[ages[ages.length - 1]];
}

/**
 * 목돈 P를 월 m원씩 n개월 동안 나눠 받을 때의 월 수령액 (기말 지급 연금).
 *   P = m·{1 − (1+i)^(−n)} / i   →   m = P·i / {1 − (1+i)^(−n)}
 */
export function monthlyPayout(principal: number, annualRatePct: number, months: number): number {
  const i = annualRatePct / 100 / 12;
  if (months <= 0) return 0;
  if (i === 0) return principal / months;
  return (principal * i) / (1 - Math.pow(1 + i, -months));
}

/** 월 m원씩 n개월 받을 때의 현재가치 (기말 지급 연금) */
export function annuityPV(monthly: number, annualRatePct: number, months: number): number {
  const i = annualRatePct / 100 / 12;
  if (months <= 0) return 0;
  if (i === 0) return monthly * months;
  return (monthly * (1 - Math.pow(1 + i, -months))) / i;
}

