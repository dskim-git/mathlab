/** 정의역 안에서만, 상자 안에서만 샘플링해 끊긴 조각들로 돌려준다 */
export function samplePath(
  fn: (x: number) => number,
  box: Box,
  dom?: [number, number],
  n = 200,
): [number, number][][] {
  const out: [number, number][][] = [];
  let cur: [number, number][] = [];
  const lo = dom ? Math.max(box.xMin, dom[0]) : box.xMin;
  const hi = dom ? Math.min(box.xMax, dom[1]) : box.xMax;
  if (hi <= lo) return out;
  for (let i = 0; i <= n; i++) {
    const x = lo + ((hi - lo) * i) / n;
    const y = fn(x);
    if (!Number.isFinite(y) || y < box.yMin || y > box.yMax) {
      if (cur.length > 1) out.push(cur);
      cur = [];
      continue;
    }
    cur.push([x, y]);
  }
  if (cur.length > 1) out.push(cur);
  return out;
}

