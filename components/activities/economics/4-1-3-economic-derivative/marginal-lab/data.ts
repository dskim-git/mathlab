// 경제함수의 미분 — 네 가지 '한계' — 활동 데이터
//
//  · 네 탭이 모두 같은 틀을 쓴다.
//        x 가 한 단위 늘 때 y 가 변하는 정도  =  Δy/Δx
//        Δx 를 0 에 한없이 가까이 보내면      =  f'(x)   (순간변화율)
//    그래서 도함수가 곧 '한계○○함수' 이고, 미분계수 f'(a) 가 'x = a 에서의 한계○○' 다.
//        효용함수   U(x) → U'(x) 한계효용함수
//        비용함수   C(x) → C'(x) 한계비용함수
//        생산함수   P(x) → P'(x) 한계생산함수
//        수입함수   g(x) = x·f(x) → g'(x) 한계수입함수   (f 는 가격 x 에 대한 판매량)
//
//  · 이차함수에서는 [k, k+1] 구간의 평균변화율이 그 구간의 한가운데 k + 0.5 에서의
//    미분계수와 정확히 같다.
//        U(x) = ax^2 + bx 일 때  (U(k+1) - U(k))/1 = a(2k+1) + b = U'(k + 0.5)
//    탭 ① 에서 '한 개씩' 의 계단 막대와 한계효용함수의 직선을 겹쳐 그려 이것을 보인다.
//
// ── 탭 ① 한계효용 ────────────────────────────────────────
//  · 세 장면 모두 U(x) = ax^2 + bx 꼴이라 한 개씩 늘 때의 한계효용이 등차로 줄어든다.
//        🧊 아이스 레모네이드  U(x) = -x^2 + 13x
//           0 12 22 30 36 40 42 42 40   증분 12 10 8 6 4 2 0 -2   U'(x) = -2x + 13
//        🎤 노래방 한 곡        U(x) = -x^2 + 16x
//           0 15 28 39 48 55 60 63 64   증분 15 13 11 9 7 5 3 1   U'(x) = -2x + 16
//        🍕 피자 한 조각        U(x) = -2x^2 + 22x
//           0 20 36 48 56 60 60 56 48   증분 20 16 12 8 4 0 -4 -8  U'(x) = -4x + 22
//    레모네이드는 7잔째에 한계효용이 0, 8잔째에 음수가 되고 피자는 6조각째에 0 이 된다.
//    '한 개 더 먹어도 더 좋아지지 않는 자리' 가 눈에 보이게 값을 골랐다.
//  · Δx 를 1 → 1/2 → 1/4 → 1/8 → 1/16 로 줄이면 평균변화율이 U'(x0) 로 다가간다.
//        U(x) = -x^2 + 13x 에서 [x0, x0 + h] 의 평균변화율은 -(2x0 + h) + 13
//        x0 = 3 이면 h = 1, 1/2, 1/4 … 에 대해 6, 6.5, 6.75, 6.875, 6.9375 → 7
//
// ── 탭 ② 한계비용 ────────────────────────────────────────
//  · 비용함수는 고정비(상수항)가 있고 한계비용은 그것과 상관없다 — 미분하면 사라진다.
//        🧼 수제 비누   C(x) = x^3 - 12x^2 + 60x + 100 (천원)
//                       C'(x) = 3x^2 - 24x + 60 = 3((x - 4)^2 + 4)  최소 12 (x = 4)
//                       C(0..12) = 100 149 180 199 212 225 244 275 324 397 500 639 820
//                       한 개 더 만들 때의 실제 비용 49 31 19 13 13 19 31 49 73 103 139 181
//        ☕ 로스터리    C(x) = 2x^2 + 24x + 180 (천원)   C'(x) = 4x + 24  (줄곧 증가)
//        🖨️ 3D 키링     C(x) = x^3 - 6x^2 + 20x + 60 (천원)
//                       C'(x) = 3x^2 - 12x + 20 = 3(x - 2)^2 + 8   최소 8 (x = 2)
//    한계비용이 처음에는 줄다가(익숙해지고 묶음 할인) 나중에 늘어나는(야근·급히 사오는 재료)
//    U 자 모양을 두 장면에서 보고, 줄곧 늘기만 하는 장면과 견준다.
//
// ── 탭 ③ 한계생산량 ──────────────────────────────────────
//  · 노동량 x 에 대한 생산함수와 그 도함수.
//        🥐 빵집 주방   P(x) = -x^3 + 15x^2 + 72x (개)
//                       P'(x) = -3x^2 + 30x + 72 = -3(x - 12)(x + 2)
//                       최대 147 (x = 5), 0 이 되는 자리 x = 12, 그 뒤로는 음수
//                       P'(13) = -507 + 390 + 72 = -45,  P(13) = 1274
//                       P(0..14) = 0 86 196 324 464 610 756 896 1024 1134 1220 1276 1296 1274 1204
//        🥬 배추밭      P(x) = -x^2 + 20x (포기)   P'(x) = -2x + 20   0 이 되는 자리 x = 10
//        🏭 조립 라인   P(x) = 25x (개)            P'(x) = 25         늘 일정
//    사람을 더 넣어도 생산이 늘지 않는 자리(한계생산량 0)가 어디인지 찾게 한다.
//
// ── 탭 ④ 한계수입 ────────────────────────────────────────
//  · 가격 x 에 대한 판매량이 f(x) 일 때 수입은 g(x) = x·f(x) 다.
//    가격을 올리면 세로(값)는 커지고 가로(판매량)는 줄어 직사각형의 넓이가 수입이 된다.
//        🧋 버블티   f(x) = -30x + 240 (잔)   g(x) = -30x^2 + 240x   g'(x) = -60x + 240
//                    g' = 0 → x = 4, 이때 판매량 120잔, 수입 480천원 (최대)
//        🎫 공연표   f(x) = -25x + 400 (장)   g(x) = -25x^2 + 400x   g'(x) = -50x + 400
//                    g' = 0 → x = 8, 이때 200장, 1,600만원
//        📚 전자책   f(x) = -50x + 600 (권)   g(x) = -50x^2 + 600x   g'(x) = -100x + 600
//                    g' = 0 → x = 6, 이때 300권, 1,800천원
//    세 장면 모두 판매량이 0 이 되는 가격에서 수입도 0 이 되고, 그 절반 자리에서 가장 크다.
//
//  금액·개수는 모두 계산이 깔끔하게 떨어지도록 이 활동을 위해 정한 가상의 값이다.

export function fmt(v: number, d = 2): string {
  if (!Number.isFinite(v)) return "0";
  const r = Number(v.toFixed(d));
  return String(Object.is(r, -0) ? 0 : r);
}
export function won(v: number): string {
  return Math.round(v).toLocaleString("ko-KR");
}

