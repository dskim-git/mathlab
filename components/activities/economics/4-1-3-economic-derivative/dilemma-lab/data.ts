/** 두 전략을 ROUNDS 판 맞붙여 라운드별 수와 누적 점수를 돌려준다 */
export function duel(
  g: { R: number; T: number; P: number; S: number },
  a: Strategy,
  b: Strategy,
  rounds = ROUNDS,
): { moves: [Move, Move][]; scoreA: number; scoreB: number } {
  const ma: Move[] = [];
  const mb: Move[] = [];
  const moves: [Move, Move][] = [];
  let scoreA = 0;
  let scoreB = 0;
  for (let i = 0; i < rounds; i++) {
    const x = a.play(ma, mb);
    const y = b.play(mb, ma);
    ma.push(x);
    mb.push(y);
    moves.push([x, y]);
    scoreA += payoff(g, x, y);
    scoreB += payoff(g, y, x);
  }
  return { moves, scoreA, scoreB };
}

/** 모든 전략을 서로 맞붙여 총점을 낸다 (자기 자신과도 겨룬다) */
export function league(g: { R: number; T: number; P: number; S: number }): number[] {
  return STRATEGIES.map((a) => STRATEGIES.reduce((sum, b) => sum + duel(g, a, b).scoreA, 0));
}

