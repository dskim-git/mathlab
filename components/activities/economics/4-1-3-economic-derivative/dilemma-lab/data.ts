// 죄수의 딜레마 — 활동 데이터
//
//  · 두 사람이 동시에 '협력' 또는 '배신' 가운데 하나를 고르고, 네 가지 짝마다 보수가 정해진다.
//        R  둘 다 협력했을 때 (reward)
//        T  나만 배신했을 때 (temptation — 배신의 유혹)
//        P  둘 다 배신했을 때 (punishment)
//        S  나만 협력했을 때 (sucker — 혼자 손해)
//    T > R > P > S 이면 죄수의 딜레마다.
//        상대가 협력해도 (T > R) 배신이 낫고, 상대가 배신해도 (P > S) 배신이 낫다
//        → 배신이 지배전략이고, 그래서 둘 다 배신해 R 보다 못한 P 를 받는다.
//    반복해서 겨룰 때 번갈아 배신하는 것이 둘 다 협력하는 것보다 낫지 않도록
//    2R > T + S 도 함께 맞추었다.
//
//  · 다섯 상황 모두 위 두 부등식을 지킨다. 숫자는 클수록 좋은 '점수' 로 통일했다
//    (수업 자료의 형량처럼 작을수록 좋은 수로 두면 부등호가 뒤집혀 헷갈리기 때문).
//        id  상황                 R   T   P   S   2R  T+S  단위
//        g1  축제 솜사탕 부스     40  60  25  10   80   70  만원
//        g2  라면 광고 경쟁       50  70  35  20  100   90  억원
//        g3  마을 앞바다 고기잡이 30  45  12   5   60   50  상자
//        g4  조별 과제            90  95  70  60  180  155  점
//        g5  두 나라 탄소 줄이기  60  80  30  20  120  100  점
//    g4 는 배신의 유혹 T - R = 5 와 혼자 손해 P - S = 10 이 작아 협력이 비교적 쉬운 판이고,
//    g1·g3 은 그 차이가 커서 배신이 세다 — 탭 ③ 의 리그 순위가 상황마다 갈리는 까닭이다.
//
// ── 탭 ① 딜레마 실험실 ───────────────────────────────────
//  · 보수표를 띄워 두고 '상대가 협력한다면' / '상대가 배신한다면' 을 차례로 눌러
//    그때마다 내 두 선택을 견준다. 두 경우 모두 배신이 나으므로 배신이 지배전략이고,
//    그 결과 둘 다 배신한 칸이 균형이 되는데 그 칸의 보수 P 가 R 보다 작다.
//  · 축제 부스의 값: 상대가 값을 지킬 때 깎으면 60 (지키면 40), 상대가 깎을 때
//    깎으면 25 (지키면 10). 둘 다 깎아 25 씩 — 둘 다 지켰으면 40 씩이었다.
//
// ── 탭 ② 한 판 승부 ──────────────────────────────────────
//  · 네 상대와 여러 판을 직접 겨룬다. 상대의 선택은 누른 뒤에 정해지고 공개된다.
//        🕊️ 믿음이   10 판 가운데 8 판쯤 협력
//        🦊 여우     10 판 가운데 8 판쯤 배신
//        🎲 동전이   반반
//        🪞 거울이   내가 직전 판에 한 것을 그대로 따라 함 (첫 판은 협력)
//    거울이와 겨룰 때만 내 선택이 다음 판에 돌아온다 — 반복 게임의 맛보기다.
//
// ── 탭 ③ 전략 리그 ───────────────────────────────────────
//  · 여섯 전략을 10 라운드씩 맞붙인다. 모두 결정론적이라 결과가 늘 같다.
//        😇 늘 협력      언제나 협력
//        😈 늘 배신      언제나 배신
//        🪞 맞대응       첫 판 협력, 그 뒤로는 상대의 직전 선택을 따라 함
//        🪤 앙갚음       상대가 한 번이라도 배신하면 그 뒤로 끝까지 배신
//        🕊️ 너그러운 맞대응  상대가 두 판 연속 배신해야 배신
//        🔁 엇갈이       협력·배신을 번갈아 함
//  · 축제 부스(g1) 10 라운드 총점 — 자기 자신을 포함한 여섯 상대와 모두 겨룬 합
//        앙갚음 2225 > 늘 배신 2165 = 맞대응 2165 > 엇갈이 2120
//        > 너그러운 맞대응 2070 > 늘 협력 1950
//  · 조별 과제(g4) 에서는 순위가 뒤집힌다
//        앙갚음 5100 > 맞대응 5060 > 너그러운 맞대응 5030 > 늘 협력 4950
//        > 엇갈이 4810 > 늘 배신 4675
//    배신의 유혹과 혼자 손해가 작으면 협력하는 전략이 위로 올라온다는 것을 보게 한다.
//  · 맞대응 대 늘 배신(g1): 맞대응은 첫 판에 S = 10 을 받고 그 뒤 아홉 판은 P = 25
//    → 10 + 225 = 235, 늘 배신은 60 + 225 = 285.
//
// ── 탭 ④ 딜레마의 조건과 탈출 ────────────────────────────
//  · R, T, P, S 를 손잡이로 바꾸면 지배전략과 균형이 곧바로 다시 계산된다.
//        T > R 이면 상대가 협력할 때 배신이 낫고, P > S 이면 상대가 배신할 때 배신이 낫다
//        둘 다이면 배신이 지배전략, 반대이면 협력이 지배전략, 엇갈리면 지배전략이 없다
//        배신이 지배전략이면서 R > P 일 때가 죄수의 딜레마다
//  · 벌금 f 를 매기면 배신했을 때의 보수에서 f 를 뺀다 (T - f, P - f).
//    협력이 지배전략이 되려면  R > T - f  이고  S > P - f  이어야 하므로
//        f > T - R  이고  f > P - S
//    축제 부스는 T - R = 20, P - S = 15 이므로 f > 20, 곧 가장 작은 정수 벌금은 21 이다.
//
//  상황과 숫자는 모두 개념을 보여 주기 위해 이 활동에서 정한 가상의 값이다.

export function fmt(v: number, d = 2): string {
  if (!Number.isFinite(v)) return "0";
  const r = Number(v.toFixed(d));
  return String(Object.is(r, -0) ? 0 : r);
}
export function won(v: number): string {
  return Math.round(v).toLocaleString("ko-KR");
}

