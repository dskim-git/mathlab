export type Verdict = {
  /** 배신이 지배전략인가 */
  defectDominant: boolean;
  /** 협력이 지배전략인가 */
  coopDominant: boolean;
  /** 죄수의 딜레마인가 */
  dilemma: boolean;
  label: string;
  why: string;
};

export function judge(p: { R: number; T: number; P: number; S: number }): Verdict {
  const betterIfCoop = p.T > p.R;
  const betterIfDefect = p.P > p.S;
  const defectDominant = betterIfCoop && betterIfDefect;
  const coopDominant = p.R > p.T && p.S > p.P;
  const dilemma = defectDominant && p.R > p.P;
  if (dilemma)
    return {
      defectDominant,
      coopDominant,
      dilemma,
      label: "죄수의 딜레마",
      why: "상대가 무엇을 하든 배신이 나아 둘 다 배신하는데, 그 결과가 둘 다 협력했을 때보다 못해요.",
    };
  if (defectDominant)
    return {
      defectDominant,
      coopDominant,
      dilemma,
      label: "배신이 지배전략 (딜레마는 아님)",
      why: "배신이 지배전략이지만 둘 다 배신한 결과가 둘 다 협력한 결과보다 나빠지지는 않아요.",
    };
  if (coopDominant)
    return {
      defectDominant,
      coopDominant,
      dilemma,
      label: "협력이 지배전략",
      why: "상대가 무엇을 하든 협력이 나아요. 서로 믿을 필요도 없이 협력이 이루어집니다.",
    };
  return {
    defectDominant,
    coopDominant,
    dilemma,
    label: "지배전략이 없음",
    why: "상대가 무엇을 하느냐에 따라 내게 좋은 선택이 달라져요. 상대의 마음을 읽어야 하는 판입니다.",
  };
}

