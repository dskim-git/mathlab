// 공급의 가격 탄력성 — 활동 데이터
//
// ─── 다루는 개념 ───────────────────────────────────────────
//  공급의 가격 탄력성은 가격의 변화에 공급량이 얼마나 민감하게 반응하는지를 재는 수다.
//
//      (가격의 변화율)   = (x1 - x0) / x0
//      (공급량의 변화율) = (f(x1) - f(x0)) / f(x0)
//      e_s = (공급량의 변화율) / (가격의 변화율)
//
//  * 수요와 달리 음의 부호를 붙이지 않는다.
//    공급의 법칙으로 값이 오르면 공급량도 늘어 두 변화율의 부호가 이미 같기 때문이다.
//
//  판별은 수요와 똑같이 1 을 기준으로 한다 —  e > 1 탄력적 ·  e = 1 단위 탄력적 ·  0 < e < 1 비탄력적.
//
//  인상폭을 한없이 줄이면 그 비가 한 수에 모이고, 그것이 미분을 쓴 식이다.
//      e_s = x f'(x) / f(x)
//
// ─── 공급 탄력성에만 있는 성질 (이 활동의 뼈대) ────────────────
//  (1) 일차 공급함수 f(x) = ax + b (a > 0, f(x) > 0) 에서
//          e_s = a x / (a x + b)
//      이고, 판정은 b 의 부호만으로 정해진다 — 가격 x 와는 상관이 없다.
//          b > 0  →  a x + b > a x  →  0 < e < 1      어느 가격에서나 비탄력적
//          b = 0  →  e = 1                            어느 가격에서나 단위 탄력적
//          b < 0  →  0 < a x + b < a x  →  e > 1      어느 가격에서나 탄력적
//      수요 쪽(일차 수요함수)에서는 가격마다 판정이 달라졌으므로 좋은 대조가 된다.
//
//  (2) 그림으로 보면  e_s = (접선의 기울기) / (원점에서 그 점까지의 기울기) 다.
//          원점선의 기울기 = f(x)/x = a + b/x
//      이므로 b < 0 이면 공급선이 원점선보다 가파르고(탄력적),
//      b > 0 이면 원점선이 더 가파르며(비탄력적), b = 0 이면 두 선이 포개진다(단위 탄력적).
//
//  (3) 멱함수 f(x) = k x^n 은 f' = k n x^(n-1) 이므로
//          e_s = x · k n x^(n-1) / (k x^n) = n
//      어느 가격에서나 지수 n 이 그대로 탄력성이 된다.
//
//  (4) 기준점 (x0, q0) 를 지나면서 탄력성이 e 인 일차 공급함수는
//          a = e q0 / x0,   b = q0 (1 - e)
//      로 하나로 정해진다. e 가 커질수록 a 가 커져 공급선이 그 점을 축으로 가팔라진다.
//      탭 ④ 는 이 식으로 '같은 상품의 기간별 공급곡선'을 만든다.
//
// ─── 쓴 공급함수 (수업 자료·앞 활동과 겹치지 않게 새로 골랐다) ──────
//  수업 자료의 f(x) = x + 20, f(x) = 3x - 12 와 햄버거 · 배추 예시는 쓰지 않았다.
//  같은 소단원 앞 활동(elasticity_lab)의 수요함수와 상품 이름도 모두 피했다.
//
//  탭 ① 공장 실험실 — 가격을 5 ~ 25% 올려 보고 e_s 를 구한다 (모두 일차라 폭과 무관)
//      탄산음료 공장  f = 6x - 90    x0 = 30  q0 = 90   e = 180/90  = 2     탄력적
//      굴 양식장     f = 2x + 50    x0 = 25  q0 = 100  e = 50/100  = 0.5   비탄력적
//      도자기 공방    f = 4x         x0 = 30  q0 = 120  e = 120/120 = 1     단위 탄력적
//      배달 기사     f = 10x - 120  x0 = 20  q0 = 80   e = 200/80  = 2.5   탄력적
//      검산 (10% 인상):
//        음료   x1 = 33,   f = 108,  Δq/q0 = 18/90  = 0.2   → e = 2
//        굴     x1 = 27.5, f = 105,  Δq/q0 = 5/100  = 0.05  → e = 0.5
//        도자기  x1 = 33,   f = 132,  Δq/q0 = 12/120 = 0.1   → e = 1
//        배달   x1 = 22,   f = 100,  Δq/q0 = 20/80  = 0.25  → e = 2.5
//
//  탭 ② 절편의 비밀 — a 와 b 를 손잡이로 움직이며 세 영역을 모두 만든다
//      a 는 1 ~ 8 (정수), b 는 -80 ~ 80 (10 단위), 가격 x 는 공급량이 양수인 자리부터
//
//  탭 ③ 좁혀 보기 — 인상폭을 20% 에서 0.1% 까지 줄이며 점 탄력성으로 모이는 것을 본다
//      곧은 공급   f = 2x + 50     x0 = 25  q0 = 100  점 e = 0.5  (폭과 무관하게 늘 0.5)
//      가속 공급   f = 0.1x^2 + 10 x0 = 20  q0 = 50   점 e = 1.6
//      제곱 공급   f = 0.2x^2      x0 = 15  q0 = 45   점 e = 2    (멱함수라 어디서나 2)
//      손으로 푼 구간 탄력성 (인상폭 d):
//        제곱 공급  ((1+d)^2 - 1)/d = 2 + d        → d → 0 에서 2
//        가속 공급  0.8(2d + d^2)/d = 1.6 + 0.8d   → d → 0 에서 1.6
//      그래서 20% 에서는 2.2 와 1.76, 0.1% 에서는 2.001 과 1.6008 이 된다.
//
//  탭 ④ 시간이 흐르면 — 같은 상품의 공급곡선이 기간에 따라 기준점을 축으로 회전한다
//      딸기 농장      x0 = 30  q0 = 120  e = 0.05 · 0.2 · 0.6 · 2.5
//      수제 가구 공방  x0 = 40  q0 = 80   e = 0.1  · 0.5 · 1.2 · 3
//      편의점 도시락   x0 = 5   q0 = 100  e = 0.8  · 2   · 3.5 · 5
//      도심 아파트     x0 = 50  q0 = 60   e = 0.02 · 0.05 · 0.1 · 0.4
//      (a = e q0/x0, b = q0(1 - e) 로 만든다. 딸기 한 해는 a = 10, b = -180 → f = 10x - 180)
//      기간은 하루 · 일주일 · 한 달 · 한 해. 아파트는 한 해가 지나도 여전히 비탄력적이다.
//
//  탭 ⑤ 조절 속도 창고 — 가격을 10% 올렸을 때 공급량 변화로 가른다
//      탄력적   창고의 티셔츠 +18% (e 1.8) · 내려받는 전자책 +35% (e 3.5)
//              인쇄소의 전단지 +24% (e 2.4) · 호출 택시 +13% (e 1.3)
//      비탄력적 공연장 좌석 +1% (e 0.1) · 유전의 원유 +2% (e 0.2)
//              10년 숙성 와인 +3% (e 0.3) · 바닷가 땅 +0.5% (e 0.05)
//
//  이 활동의 공급함수 · 공급량 · 변화율은 모두 개념을 보여 주기 위해 정한 가상의 값이다.

export function fmt(v: number, d = 2): string {
  if (!Number.isFinite(v)) return "0";
  const r = Number(v.toFixed(d));
  return String(Object.is(r, -0) ? 0 : r);
}
export function pct(v: number, d = 1): string {
  return `${v > 0 ? "+" : ""}${fmt(v * 100, d)}%`;
}
export function won(v: number): string {
  return Math.round(v).toLocaleString("ko-KR");
}

