export function bFloor(a: number): number {
  return Math.max(B_MIN, -40 * a);
}

/** 공급량이 양수가 되는 가장 작은 정수 가격 */
export function priceFloor(a: number, b: number): number {
  return Math.max(1, Math.floor(-b / a) + 1);
}

/** a, b 에 맞춰 보기 좋은 상자를 만든다 */
export function supplyBox(a: number, b: number): Box {
  const top = Math.max(60, a * X_VIEW + b + 20);
  const gy = top <= 120 ? 20 : top <= 300 ? 50 : 100;
  return {
    xMin: 0,
    xMax: X_VIEW + 5,
    yMin: 0,
    yMax: Math.ceil(top / gy) * gy,
    gx: 10,
    gy,
  };
}

