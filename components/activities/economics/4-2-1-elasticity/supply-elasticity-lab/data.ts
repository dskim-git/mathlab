export function eKind(e: number): EKind {
  if (Math.abs(e - 1) < 1e-9) return "unit";
  return e > 1 ? "elastic" : "inelastic";
}

/** 점 탄력성 — 공급은 음의 부호를 붙이지 않는다 */
export function pointEs(f: (x: number) => number, d1: (x: number) => number, x: number): number {
  return (x * d1(x)) / f(x);
}

/** 구간 탄력성 — 두 변화율의 비 (공급은 부호가 같아 그대로 양수가 된다) */
export function arcEs(f: (x: number) => number, x0: number, x1: number): number {
  const dq = (f(x1) - f(x0)) / f(x0);
  const dx = (x1 - x0) / x0;
  return dq / dx;
}

/** 기준점 (x0, q0) 를 지나면서 탄력성이 e 인 일차 공급함수의 계수 */
export function lineFromE(x0: number, q0: number, e: number): { a: number; b: number } {
  return { a: (e * q0) / x0, b: q0 * (1 - e) };
}

