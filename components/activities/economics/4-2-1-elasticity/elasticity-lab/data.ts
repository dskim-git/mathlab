export function eKind(e: number): EKind {
  if (Math.abs(e - 1) < 1e-9) return "unit";
  return e > 1 ? "elastic" : "inelastic";
}

/** 점 탄력성 — 미분을 쓴 식 */
export function pointE(f: (x: number) => number, d1: (x: number) => number, x: number): number {
  return (-x * d1(x)) / f(x);
}

/** 구간 탄력성 — 두 변화율의 비 */
export function arcE(f: (x: number) => number, x0: number, x1: number): number {
  const dq = (f(x1) - f(x0)) / f(x0);
  const dx = (x1 - x0) / x0;
  return -dq / dx;
}

