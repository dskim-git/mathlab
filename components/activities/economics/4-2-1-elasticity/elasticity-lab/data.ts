// 수요의 가격 탄력성 — 활동 데이터
//
// ─── 다루는 개념 ───────────────────────────────────────────
//  수요의 가격 탄력성은 가격의 변화에 수요량이 얼마나 민감하게 반응하는지를 재는 수다.
//
//      (가격의 변화율) = (x1 - x0) / x0
//      (수요량의 변화율) = (f(x1) - f(x0)) / f(x0)
//      e_d = - (수요량의 변화율) / (가격의 변화율)
//
//  수요의 법칙으로 두 변화율은 보통 부호가 반대라, 앞에 음의 부호를 붙여 양수로 만든다.
//  판별은 1 을 기준으로 한다 —  e > 1 탄력적 ·  e = 1 단위 탄력적 ·  0 < e < 1 비탄력적.
//
//  할인폭을 한없이 줄이면 이 비는 한 수에 모이고, 그것이 미분을 쓴 식이다.
//      e_d = - x f'(x) / f(x)
//  까닭:  (수요량의 변화율)/(가격의 변화율) = (Δq/q0) / (Δx/x0) = (Δq/Δx) · (x0/q0)
//         이고 Δx → 0 에서 Δq/Δx → f'(x0) 이므로  x0 f'(x0) / f(x0) 가 된다.
//
//  * 일차 수요함수에서는 Δq/Δx 가 기울기 -a 로 늘 같아서, 할인폭이 아무리 커도
//    구간 탄력성이 점 탄력성과 처음부터 똑같다. 수렴을 보려면 일차가 아닌 함수가 필요하다.
//    그래서 탭 ② 에 쌍곡선형과 이차형을 함께 두었다.
//
//  수입(총수입) R(x) = x f(x) 를 미분하면
//      R'(x) = f(x) + x f'(x) = f(x) · (1 - e_d)
//  이므로 f(x) > 0 인 곳에서 R' = 0 ⟺ e_d = 1 이다.
//  즉 수입이 가장 커지는 가격이 바로 단위 탄력적인 가격이다 (탭 ④ 의 뼈대).
//      e > 1 (탄력적)  : 가격을 올리면 수입이 줄고, 내리면 수입이 는다
//      e < 1 (비탄력적): 가격을 올리면 수입이 늘고, 내리면 수입이 준다
//
// ─── 쓴 수요함수 (수업 자료의 것과 겹치지 않게 새로 골랐다) ──────
//  수업 자료의 f(x) = -2x + 180,  f(x) = -x + 50,  f(x) = -2x + 100 과
//  쌀 · 셔츠 · 사이다 · 소금 예시는 쓰지 않았다.
//
//  일차 수요함수 f(x) = -ax + b 에서  e(x) = ax / (b - ax),  단위 탄력점은 x = b / (2a).
//
//    A  f(x) = -3x + 180   e(x) = x/(60 - x)    단위 탄력 x = 30,  f(30) = 90
//    B  f(x) = -x + 120    e(x) = x/(120 - x)   단위 탄력 x = 60,  f(60) = 60
//    C  f(x) = -5x + 400   e(x) = x/(80 - x)    단위 탄력 x = 40,  f(40) = 200
//    D  f(x) = -3x + 250   e(40)? -> 아래 ① 참고, 단위 탄력 x = 125/3 (화면에서 쓰지 않음)
//    E  f(x) = 2400/x      e(x) = 1  (어느 가격에서나 단위 탄력적)
//    F  f(x) = 14400/x^2   e(x) = 2  (어느 가격에서나 탄력적)
//    G  f(x) = 3600/x      e(x) = 1
//    H  f(x) = 300 - 2x^2  e(x) = 4x^2 / (300 - 2x^2),  e(10) = 400/100 = 4
//
//  쌍곡선형 f = k/x 는 f' = -k/x^2 이므로 e = -x(-k/x^2)/(k/x) = 1 — 늘 단위 탄력적.
//  f = k/x^2 은 f' = -2k/x^3 이므로 e = 2 — 늘 탄력적.
//
// ─── 탭 ─────────────────────────────────────────────────────
//  ① 할인 실험실   네 상품을 5~25% 할인해 보고 두 변화율의 비로 e 를 구한다.
//                  모두 일차 수요함수라 할인폭을 바꿔도 e 가 변하지 않는다.
//                    무선 이어폰  f = -3x + 180,  x0 = 40,  q0 = 60,   e = 2     탄력적
//                    우산        f = -x + 120,   x0 = 20,  q0 = 100,  e = 0.2   비탄력적
//                    조각 케이크  f = -5x + 400,  x0 = 40,  q0 = 200,  e = 1     단위 탄력적
//                    보조배터리   f = -3x + 250,  x0 = 50,  q0 = 100,  e = 1.5   탄력적
//                  검산 (할인 10%):
//                    이어폰 x1 = 36, f = 72,  Δq/q0 = 12/60  = 0.2   → e = 2
//                    우산   x1 = 18, f = 102, Δq/q0 = 2/100  = 0.02  → e = 0.2
//                    케이크 x1 = 36, f = 220, Δq/q0 = 20/200 = 0.1   → e = 1
//                    배터리 x1 = 45, f = 115, Δq/q0 = 15/100 = 0.15  → e = 1.5
//                  할인폭 5 · 10 · 15 · 20 · 25% 에서 x1 이 모두 깔끔한 수가 되도록 x0 를 골랐다.
//
//  ② 좁혀 보기     할인폭을 20% 에서 0.1% 까지 줄이며 구간 탄력성이 점 탄력성으로 모이는 것을 본다.
//                    곧은 수요    f = -3x + 180,  x0 = 40 → 점 e = 2    (할인폭과 무관하게 늘 2)
//                    쌍곡선 수요  f = 3600/x,     x0 = 30 → 점 e = 1
//                    가파른 수요  f = 300 - 2x^2, x0 = 10 → 점 e = 4
//                  검산 (쌍곡선, x0 = 30, q0 = 120):
//                    20% → x1 = 24,   f = 150,     Δq/q0 =  0.25    → e = 1.25
//                    10% → x1 = 27,   f = 133.33,  Δq/q0 =  0.1111  → e = 1.1111
//                     1% → x1 = 29.7, f = 121.212, Δq/q0 =  0.0101  → e = 1.0101
//                  검산 (가파른, x0 = 10, q0 = 100):
//                    20% → x1 = 8,    f = 172,     Δq/q0 =  0.72    → e = 3.6
//                    10% → x1 = 9,    f = 138,     Δq/q0 =  0.38    → e = 3.8
//                     1% → x1 = 9.9,  f = 103.98,  Δq/q0 =  0.0398  → e = 3.98
//
//  ③ 탄력성 판별기 가격을 움직이며 e 를 보고 탄력적 · 단위 탄력적 · 비탄력적을 가린다.
//                    A f = -3x + 180   x 5~55    단위 탄력 x = 30
//                    B f = -x + 120    x 10~110  단위 탄력 x = 60
//                    E f = 2400/x      x 10~60   어디서나 e = 1
//                    F f = 14400/x^2   x 10~40   어디서나 e = 2
//                  일차 수요함수에서는 가격이 높을수록 탄력적이 된다는 것을 눈으로 본다.
//
//  ④ 사장님의 선택 수입 R(x) = x f(x) 를 수요곡선과 나란히 놓고 최대 수입 가격을 찾는다.
//                    A f = -3x + 180  R = -3x^2 + 180x  최대 x = 30, R = 2700
//                    B f = -x + 120   R = -x^2 + 120x   최대 x = 60, R = 3600
//                    C f = -5x + 400  R = -5x^2 + 400x  최대 x = 40, R = 8000
//                  세 경우 모두 최대 수입 가격이 단위 탄력 가격과 같다.
//
//  ⑤ 대체재 창고   가격을 10% 올렸을 때의 수요량 변화로 e 를 읽고 탄력 · 비탄력으로 가른다.
//                  대체재가 많을수록 탄력적이라는 것을 여덟 사례로 겪는다.
//                    탄력적   브랜드 생수 -25% (e 2.5) · 배달 피자 -18% (e 1.8)
//                            해외여행 항공권 -32% (e 3.2) · 영화관 관람 -14% (e 1.4)
//                    비탄력적 수돗물 -2% (e 0.2) · 통학 교통비 -4% (e 0.4)
//                            처방약 -1% (e 0.1) · 교복 -6% (e 0.6)
//                  수입 변화율 = (1 + 0.1)(1 + Δq/q) - 1 로 검산하면
//                    2.5 → -17.5%, 1.8 → -9.8%, 3.2 → -25.2%, 1.4 → -5.4%
//                    0.2 → +7.8%,  0.4 → +5.6%, 0.1 → +8.9%,  0.6 → +3.4%
//                  탄력적인 것은 모두 수입이 줄고 비탄력적인 것은 모두 수입이 늘어,
//                  ④ 에서 본 규칙과 들어맞는다.
//
//  이 활동의 수요함수 · 판매량 · 변화율은 모두 개념을 보여 주기 위해 정한 가상의 값이다.

export function fmt(v: number, d = 2): string {
  if (!Number.isFinite(v)) return "0";
  const r = Number(v.toFixed(d));
  return String(Object.is(r, -0) ? 0 : r);
}
export function pct(v: number, d = 1): string {
  return `${v > 0 ? "+" : ""}${fmt(v * 100, d)}%`;
}
export function won(v: number): string {
  return Math.round(v).toLocaleString("ko-KR");
}

export type Piece = { pre?: string; tex?: string; post?: string };
export type Box = { xMin: number; xMax: number; yMin: number; yMax: number; gx: number; gy: number };

export function samplePath(
  fn: (x: number) => number,
  from: number,
  to: number,
  box: Box,
  n = 240,
): [number, number][][] {
  const out: [number, number][][] = [];
  let cur: [number, number][] = [];
  const lo = Math.max(from, box.xMin);
  const hi = Math.min(to, box.xMax);
  if (hi <= lo) return out;
  for (let i = 0; i <= n; i++) {
    const x = lo + ((hi - lo) * i) / n;
    const y = fn(x);
    if (!Number.isFinite(y) || y < box.yMin || y > box.yMax) {
      if (cur.length > 1) out.push(cur);
      cur = [];
      continue;
    }
    cur.push([x, y]);
  }
  if (cur.length > 1) out.push(cur);
  return out;
}

