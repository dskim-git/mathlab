/** 27장 세계 — 번호를 모양·색깔·개수로 푼다 (무늬는 언제나 채움) */
export function dec3(k: number): Sym {
  return { s: Math.floor(k / 9), c: Math.floor(k / 3) % 3, n: k % 3, h: 0 };
}
export function enc3(a: Sym): number {
  return a.s * 9 + a.c * 3 + a.n;
}
/** 81장 세계 — 무늬까지 포함해서 푼다 */
export function dec4(k: number): Sym {
  return { s: Math.floor(k / 27), c: Math.floor(k / 9) % 3, n: Math.floor(k / 3) % 3, h: k % 3 };
}

/** 세 장이 '합'인가 — withShade 이면 무늬까지 따진다 */
export function isSet(a: Sym, b: Sym, c: Sym, withShade = false): boolean {
  if ((a.s + b.s + c.s) % 3 !== 0) return false;
  if ((a.c + b.c + c.c) % 3 !== 0) return false;
  if ((a.n + b.n + c.n) % 3 !== 0) return false;
  if (withShade && (a.h + b.h + c.h) % 3 !== 0) return false;
  return true;
}

/** 속성 하나의 상태 — 0 모두 같음 · 1 모두 다름 · 2 두 장만 같음(합이 아님) */
export function attrState(v: number[]): 0 | 1 | 2 {
  if (v[0] === v[1] && v[1] === v[2]) return 0;
  if (v[0] !== v[1] && v[1] !== v[2] && v[0] !== v[2]) return 1;
  return 2;
}
