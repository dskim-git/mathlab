/** 두 장이 정해지면 합이 되는 나머지 한 장은 언제나 딱 하나 */
export function thirdSym(a: Sym, b: Sym): Sym {
  const t = (x: number, y: number) => (6 - x - y) % 3;
  return { s: t(a.s, b.s), c: t(a.c, b.c), n: t(a.n, b.n), h: t(a.h, b.h) };
}

/** 늘어놓은 카드에서 합을 모두 찾는다 (자리 번호 세 개씩) */
export function findAllSets(cards: Sym[], withShade = false): number[][] {
  const out: number[][] = [];
  for (let i = 0; i < cards.length; i++)
    for (let j = i + 1; j < cards.length; j++)
      for (let k = j + 1; k < cards.length; k++)
        if (isSet(cards[i], cards[j], cards[k], withShade)) out.push([i, j, k]);
  return out;
}

export function shuffle<T>(xs: T[]): T[] {
  const a = [...xs];
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
}

