// 유리함수의 그래프 — 활동 데이터
//
//  [y = k/x (k ≠ 0)] 두 가지가 한눈에 보이는 가장 단순한 유리함수의 그래프.
//        · 정의역 = 치역 = 0 을 뺀 실수 전체. x = 0 은 분모를 0 으로 만들고,
//          k ≠ 0 이므로 y = 0 이 되게 하는 x 도 없다.
//        · 원점대칭이다. f(−x) = k/(−x) = −k/x = −f(x) 이므로 (a, b) 가 그래프 위에 있으면
//          (−a, −b) 도 그래프 위에 있다.
//        · k > 0 이면 x 와 y 의 부호가 같아 제1·3사분면, k < 0 이면 부호가 달라 제2·4사분면에 놓인다.
//        · |k| 가 커질수록 같은 x 에서 |y| 가 커지므로 곡선이 원점에서 멀어진다.
//        · x축과 y축이 점근선이다. 곡선 위의 점이 한없이 가까워지지만 결코 만나지 않는 직선이다.
//        · 그래프 위의 점은 언제나 xy = k 를 만족한다.
//
//  [y = k/(x−p) + q] y = k/x 를 x축 방향으로 p, y축 방향으로 q 만큼 평행이동한 그래프.
//        · 정의역은 x ≠ p 인 실수 전체, 치역은 y ≠ q 인 실수 전체.
//        · 점근선은 x = p 와 y = q 이고, 두 점근선이 만나는 점 (p, q) 에 대하여 대칭이다.
//        · 모양(휘어진 정도와 놓이는 방향)은 k 가 혼자 정한다. p, q 는 자리만 옮긴다.
//        · 점근선 두 개와 지나는 점 하나를 알면 k, p, q 가 하나로 정해진다.
//
//  [y = (ax+b)/(cx+d)] c ≠ 0, ad − bc ≠ 0 일 때 비로소 점근선이 있는 곡선이 된다.
//        · c = 0 이면 y = (a/d)x + b/d 라 다항함수(직선)이다.
//        · ad − bc = 0 이면 분자가 분모의 상수배라 약분되어 상수함수가 된다.
//          보기를 들어 (2x+6)/(x+3) = 2 (단 x ≠ −3) 이고, 그래프는 한 점이 빠진 가로선이다.
//        · c ≠ 0, ad − bc ≠ 0 이면 분자를 분모로 나누어 y = k/(x−p) + q 꼴로 고칠 수 있다.
//          몫이 가로 점근선의 높이 q 가 되고 나머지가 k 가 된다.
//          c = 1 인 경우 (ax+b)/(x+d) = a + (b − ad)/(x + d) 이므로 p = −d, q = a, k = b − ad 이다.
//        · 세로 점근선은 분모를 0 으로 만드는 x = −d/c, 가로 점근선은 x 가 한없이 커질 때
//          다가가는 값 y = a/c 다.
//
//  [일상] 넓이가 36 m² 인 직사각형 텃밭의 가로가 x m 이면 세로는 36/x m 로 y = k/x 꼴이고,
//        대절비 300000 원을 x 명이 나누고 입장료 8000 원을 더하면 y = 300000/x + 8000 로
//        y = k/x + q 꼴이며, 20 명 평균이 72 점인 반에 100 점짜리 x 명이 들어오면
//        평균은 (1440 + 100x)/(20 + x) 로 (ax+b)/(cx+d) 꼴이다.
//        세 상황 모두 점근선이 "한없이 가까워지지만 닿지 못하는 값"이라는 뜻을 그대로 가진다.

