export type View = { xMin: number; xMax: number; yMin: number; yMax: number };

/** 네 탭이 함께 쓰는 정사각 좌표평면 */
export const VIEW: View = { xMin: -7, xMax: 7, yMin: -7, yMax: 7 };
export const PLANE = { w: 320, h: 320, pad: 14 };

export function planeX(x: number): number {
  return PLANE.pad + ((x - VIEW.xMin) / (VIEW.xMax - VIEW.xMin)) * (PLANE.w - 2 * PLANE.pad);
}
export function planeY(y: number): number {
  return PLANE.pad + ((VIEW.yMax - y) / (VIEW.yMax - VIEW.yMin)) * (PLANE.h - 2 * PLANE.pad);
}

/**
 * y = k/(x−p) + q 의 한 가지(branch)를 창 안에서만 잘라 표본으로 뽑는다.
 * side = +1 이면 x > p 쪽, −1 이면 x < p 쪽.
 * u = side·(x−p) > 0 로 두면 y − q = (k·side)/u 이므로,
 * 창의 네 변이 주는 제약을 u 구간 하나로 합칠 수 있다.
 * u 를 기하급수 간격으로 훑어 점근선 가까이에서 촘촘해지고, 양 끝은 창 테두리에 정확히 닿는다.
 */
export function branchSamples(k: number, p: number, q: number, v: View, side: 1 | -1, n = 150): { x: number; y: number }[] {
  const A = v.yMax - q;
  const B = v.yMin - q;
  const m = k * side;
  let uLo = side === 1 ? Math.max(0, v.xMin - p) : Math.max(0, p - v.xMax);
  let uHi = side === 1 ? v.xMax - p : p - v.xMin;
  if (!(uHi > 0)) return [];
  if (m > 0) {
    if (A <= 0) return [];
    uLo = Math.max(uLo, m / A);
    if (B > 0) uHi = Math.min(uHi, m / B);
  } else {
    if (B >= 0) return [];
    uLo = Math.max(uLo, m / B);
    if (A < 0) uHi = Math.min(uHi, m / A);
  }
  if (!(uHi > uLo) || uLo <= 0) return [];
  const pts: { x: number; y: number }[] = [];
  for (let i = 0; i <= n; i++) {
    const u = uLo * Math.pow(uHi / uLo, i / n);
    pts.push({ x: p + side * u, y: q + m / u });
  }
  return pts;
}

/** 두 가지를 한꺼번에 — 렌더러는 이 배열마다 하나의 선을 그린다. */
export function curveBranches(k: number, p: number, q: number, v: View = VIEW): { x: number; y: number }[][] {
  return [branchSamples(k, p, q, v, -1), branchSamples(k, p, q, v, 1)].filter((b) => b.length > 1);
}

